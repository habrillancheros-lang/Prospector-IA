import { readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { parseCsv } from "../lib/companies/csv.ts";

const input = resolve(process.argv[2] ?? "data/indian_companies.csv");
const output = resolve("docs/dataset-profile.md");
const [rawHeaders, ...rows] = parseCsv((await readFile(input, "utf8")).replace(/^\uFEFF/, ""));
if (!rawHeaders || !rows.length) throw new Error("Dataset has no records");
const headers = rawHeaders.map((value, index) => value.trim() || `_sourceIndex${index}`);
if (new Set(headers).size !== headers.length) throw new Error("Duplicate CSV headers");
for (const [index, row] of rows.entries()) {
  if (row.length !== headers.length)
    throw new Error(`Record ${index + 1}: expected ${headers.length} cells, got ${row.length}`);
}
const missing = (value: string) => /^(?:null|none|nan|n\/a)?$/i.test(value.trim());
const escape = (value: string) => value.replace(/\|/g, "\\|").replace(/[\r\n]+/g, " ");
const counts = (index: number) => {
  const result = new Map<string, number>();
  for (const row of rows) {
    const value = row[index].trim();
    if (!missing(value)) result.set(value, (result.get(value) ?? 0) + 1);
  }
  return [...result.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "en"));
};
const lines = [
  "# Dataset profile — supplied Indian companies CSV",
  "",
  "Generated by `scripts/profile-dataset.ts`. Raw data remains ignored by Git.",
  "",
  `Source: \`${escape(input.split("/").slice(-2).join("/"))}\`. Records: **${rows.length.toLocaleString("en-US")}**. Columns: **${headers.length}**.`,
  "",
  "The user authorized adapting Phase 1 to this CSV. This is not the specified Apify JSON; fields are reported as observed, without inventing replacements.",
  "",
  "## Fields and completeness",
  "",
  "CSV cells are strings. Inferred types below describe non-missing values; blank cells and null/none/nan/n/a tokens count as missing.",
  "",
  "| Field | Inferred type | Missing | Null rate | Distinct non-missing |",
  "| --- | --- | ---: | ---: | ---: |",
];
for (const [index, header] of headers.entries()) {
  const values = rows.map((row) => row[index].trim()).filter((value) => !missing(value));
  const numeric = values.length > 0 && values.every((value) => /^[-+]?\d+(?:\.\d+)?$/.test(value));
  const type = numeric
    ? values.every((value) => Number.isSafeInteger(Number(value)))
      ? "integer-like"
      : "number-like"
    : "text";
  lines.push(
    `| ${escape(header)} | ${type} | ${rows.length - values.length} | ${(((rows.length - values.length) / rows.length) * 100).toFixed(2)}% | ${new Set(values).size} |`,
  );
}
for (const field of ["company_type", "locations"]) {
  const index = headers.indexOf(field);
  if (index < 0) continue;
  const entries = counts(index);
  lines.push(
    "",
    `## Observed ${field} values`,
    "",
    `Distinct trimmed values: **${entries.length}**. Showing the 30 most frequent values. ${field === "locations" ? "These are raw locations, not verified registered states." : "This column includes apparent locations and employee text as well as company types."}`,
    "",
    "| Value | Records |",
    "| --- | ---: |",
  );
  for (const [value, count] of entries.slice(0, 30)) lines.push(`| ${escape(value)} | ${count} |`);
}
const nameIndex = headers.indexOf("names");
const duplicateNames = nameIndex < 0 ? [] : counts(nameIndex).filter(([, count]) => count > 1);
lines.push(
  "",
  "## Schema decisions needed",
  "",
  "- Apparent field contamination: `company_type` includes locations and employee text; `locations` includes age text such as `14 years old`. Do not automatically shift cells or expose these values as valid filters. Preserve the source and flag ambiguous values during normalization.",
  "- `registeredState` and `operatingRevenueRange` are absent: distinct counts and null rates are not applicable. Locations must not be treated as registered states.",
  "- `cin`, `status`, `companyClass`, `incorporationYear`, `paidUpCapitalCr`, `ebitdaChangePct`, and `directors` are absent. `old_time` has no verified definition and must not be converted into incorporation year.",
  "- `company_type` is the observed category field; it must not silently substitute for an official company class.",
  "- `decs` is the source description column; `tags` may provide semantic text. Ratings and reviews have no documented scale or units in this file.",
  "- The unnamed first column is reported as `_sourceIndex0`. A stable company ID strategy must be selected before import; there is no CIN.",
  `- Duplicate trimmed names: **${duplicateNames.length}** distinct names covering **${duplicateNames.reduce((sum, [, count]) => sum + count, 0)}** records. Names alone cannot be assumed unique.`,
  "- Profile review is required before implementing the canonical schema, vocabulary, embeddings, or MongoDB import.",
  "",
);
await mkdir(resolve("docs"), { recursive: true });
await writeFile(output, lines.join("\n"));
console.log(
  `Profiled ${rows.length} records (${headers.length} columns); wrote docs/dataset-profile.md`,
);
